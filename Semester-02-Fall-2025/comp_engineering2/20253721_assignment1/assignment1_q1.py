# writing the mathematical operation
operation = (5 + 3) * 2 ** 2 - 10/2
print(operation)

# Explanation of the mathematical operation above:
# 1. Paretheses are evaluated first: (5 + 3) = 8
# 2. Exponentiation: 2 ** 2 = 4
# 3. Multiplication and Division are evaluated from left to right:
#    8 * 4 = 32, then 10/2 = 5
# 4. At the end, subtraction is performed is: 32 - 5.0 = 27.0 